type Key = keyof typeof sources;
type Values = Record<string, string | number>;
const definitions = Object.fromEntries(Object.entries(sources).map(([key, message]) => [key, {
  message,
  description: `Subagents supervision panel: ${key}. Preserve protocol names and identifiers.`,
}])) as Record<Key, MessageDefinition<Values>>;

export function createContent(localization?: PluginLocalization) {
  const messages = localization?.registerMessages("panel", definitions);
  return {
    localization,
    t(key: Key, values: Values = {}): string {
      return messages?.t(key, values) ?? sources[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
    },
    number(value: number): string {
      return localization?.number(value) ?? new Intl.NumberFormat().format(value);
    },
    date(value: number): string {
      const options = { dateStyle: "medium", timeStyle: "medium" } as const;
      return localization?.date(value, options) ?? new Intl.DateTimeFormat(undefined, options).format(value);
    },
    cost(value: number): string {
      // Upstream reports USD, independently of regional preferences.
      const options = { style: "currency", currency: "USD", minimumFractionDigits: 4, maximumFractionDigits: 20 } as const;
      return localization?.number(value, options) ?? new Intl.NumberFormat(undefined, options).format(value);
    },
  };
}
export type PanelContent = ReturnType<typeof createContent>;
export const englishContent = createContent();
